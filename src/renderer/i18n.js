let current = 'en';

function translate(key, vars) {
  const table = LOCALES[current] || LOCALES.en;
  let s = table[key];
  if (s === undefined) {
    s = LOCALES.en[key];
    if (s === undefined) {
      window.__i18nMissing.add(current + ':' + key);
      return key;
    }
  }
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      s = s.replaceAll('{' + k + '}', String(v));
    }
  }
  return s;
}

function setLocale(lang) {
  current = lang === 'ru' ? 'ru' : 'en';
  document.documentElement.lang = current;
  document.title = translate('app.title');
}

window.__i18nMissing = new Set();
window.t = translate;
window.setLocale = setLocale;
window.getLocale = () => current;
window.__LOCALES = LOCALES; // для тестов парности ключей
